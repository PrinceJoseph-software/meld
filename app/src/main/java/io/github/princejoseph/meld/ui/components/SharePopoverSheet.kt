@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun SharePopoverSheet(
    room: RoomDetailsUiModel,
    initialShowQr: Boolean = false,
    onDismiss: () -> Unit
) {
    val colors = MeldTheme.colors
    val context = LocalContext.current
    val view = LocalView.current
    val clipboard = LocalClipboardManager.current
    val sheetState = rememberModalBottomSheetState(skipPartiallyExpanded = true)

    var copied by remember { mutableStateOf(false) }
    var qrGenerated by remember(initialShowQr) { mutableStateOf(initialShowQr) }

    LaunchedEffect(copied) {
        if (copied) {
            delay(2000)
            copied = false
        }
    }

    ModalBottomSheet(
        onDismissRequest = onDismiss,
        sheetState = sheetState,
        containerColor = colors.surfaceElevated,
        contentColor = colors.inkPrimary
    ) {
        Column(
            modifier = Modifier
                .fillMaxWidth()
                .navigationBarsPadding()
                .padding(horizontal = 24.dp)
                .padding(bottom = 24.dp),
            horizontalAlignment = Alignment.CenterHorizontally
        ) {
            Text(
                text = stringResource(R.string.share_popover_title),
                fontFamily = InstrumentSerifFamily,
                fontSize = 26.sp,
                color = colors.inkPrimary
            )
            Spacer(modifier = Modifier.height(4.dp))
            Text(
                text = stringResource(R.string.share_popover_subtitle),
                fontFamily = PlusJakartaSansFamily,
                fontSize = 13.sp,
                color = colors.inkSecondary
            )

            Spacer(modifier = Modifier.height(16.dp))

            // Room URL & Room Code pill
            Row(
                modifier = Modifier
                    .fillMaxWidth()
                    .clip(RoundedCornerShape(10.dp))
                    .background(colors.surfaceInset)
                    .border(1.dp, colors.hairline, RoundedCornerShape(10.dp))
                    .padding(horizontal = 14.dp, vertical = 12.dp),
                verticalAlignment = Alignment.CenterVertically,
                horizontalArrangement = Arrangement.SpaceBetween
            ) {
                Text(
                    text = room.shareUrl,
                    fontFamily = JetBrainsMonoFamily,
                    fontWeight = FontWeight.Medium,
                    fontSize = 12.sp,
                    color = colors.inkPrimary
                )
                Text(
                    text = "#${room.id}",
                    fontFamily = JetBrainsMonoFamily,
                    fontWeight = FontWeight.SemiBold,
                    fontSize = 11.sp,
                    color = colors.vermilion
                )
            }

            Spacer(modifier = Modifier.height(14.dp))

            // Generate QR Code toggle button inside SharePopover
            OutlinedButton(
                onClick = {
                    view.performTactileConfirm()
                    qrGenerated = !qrGenerated
                },
                modifier = Modifier
                    .fillMaxWidth()
                    .height(48.dp)
                    .testTag("generate_qr_code_button"),
                shape = RoundedCornerShape(12.dp),
                border = BorderStroke(
                    width = 1.dp,
                    color = if (qrGenerated) colors.vermilion else colors.hairline
                ),
                colors = ButtonDefaults.outlinedButtonColors(
                    containerColor = if (qrGenerated) colors.vermilion.copy(alpha = 0.08f) else colors.surfaceInset,
                    contentColor = if (qrGenerated) colors.vermilion else colors.inkPrimary
                )
            ) {
                Icon(
                    imageVector = Icons.Outlined.QrCode2,
                    contentDescription = null,
                    modifier = Modifier.size(18.dp)
                )
                Spacer(modifier = Modifier.width(8.dp))
                Text(
                    text = stringResource(
                        if (qrGenerated) R.string.action_hide_qr else R.string.action_generate_qr
                    ),
                    fontFamily = PlusJakartaSansFamily,
                    fontWeight = FontWeight.SemiBold,
                    fontSize = 14.sp
                )
            }

            // Animated visual QR Code expansion
            AnimatedVisibility(
                visible = qrGenerated,
                enter = expandVertically(spring(stiffness = 380f, dampingRatio = 0.78f)) +
                    scaleIn(initialScale = 0.92f) + fadeIn(),
                exit = shrinkVertically() + fadeOut()
            ) {
                Column(
                    modifier = Modifier.padding(top = 16.dp),
                    horizontalAlignment = Alignment.CenterHorizontally
                ) {
                    Box(
                        modifier = Modifier
                            .clip(RoundedCornerShape(16.dp))
                            .background(Color.White)
                            .border(1.dp, colors.hairline, RoundedCornerShape(16.dp))
                            .padding(18.dp)
                            .testTag("qr_code_matrix_box")
                    ) {
                        QrCodeMatrix(
                            content = room.shareUrl,
                            modifier = Modifier.size(196.dp)
                        )
                    }
                    Spacer(modifier = Modifier.height(8.dp))
                    Text(
                        text = stringResource(R.string.qr_ready_caption, room.id),
                        fontFamily = JetBrainsMonoFamily,
                        fontSize = 11.sp,
                        color = colors.inkSecondary
                    )
                }
            }

            Spacer(modifier = Modifier.height(16.dp))

            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.spacedBy(12.dp)
            ) {
                OutlinedButton(
                    onClick = {
                        view.performTactileConfirm()
                        clipboard.setText(AnnotatedString(room.shareUrl))
                        copied = true
                    },
                    modifier = Modifier
                        .weight(1f)
                        .height(48.dp)
                        .testTag("popover_copy_link_button"),
                    shape = RoundedCornerShape(12.dp),
                    border = BorderStroke(1.dp, if (copied) colors.emerald else colors.hairline)
                ) {
                    AnimatedContent(targetState = copied, label = "popover_copy_state") { isCopied ->
                        Row(
                            verticalAlignment = Alignment.CenterVertically,
                            horizontalArrangement = Arrangement.spacedBy(6.dp)
                        ) {
                            Icon(
                                imageVector = if (isCopied) Icons.Outlined.Check else Icons.Outlined.ContentCopy,
                                contentDescription = null,
                                tint = if (isCopied) colors.emerald else colors.inkPrimary,
                                modifier = Modifier.size(16.dp)
                            )
                            Text(
                                text = stringResource(
                                    if (isCopied) R.string.action_link_copied else R.string.action_share_link
                                ),
                                fontFamily = PlusJakartaSansFamily,
                                fontWeight = FontWeight.SemiBold,
                                fontSize = 13.sp,
                                color = if (isCopied) colors.emerald else colors.inkPrimary
                            )
                        }
                    }
                }

                Button(
                    onClick = {
                        view.performTactileTick()
                        val sendIntent = Intent(Intent.ACTION_SEND).apply {
                            type = "text/plain"
                            putExtra(
                                Intent.EXTRA_TEXT,
                                "${room.question}\nVote instantly on Meld (no login):\n${room.shareUrl}"
                            )
                        }
                        runCatching {
                            context.startActivity(Intent.createChooser(sendIntent, null))
                        }
                    },
                    modifier = Modifier
                        .weight(1f)
                        .height(48.dp)
                        .testTag("popover_system_share_button"),
                    shape = RoundedCornerShape(12.dp),
                    colors = ButtonDefaults.buttonColors(
                        containerColor = colors.inkPrimary,
                        contentColor = colors.canvas
                    )
                ) {
                    Icon(
                        imageVector = Icons.Outlined.Share,
                        contentDescription = null,
                        modifier = Modifier.size(16.dp)
                    )
                    Spacer(modifier = Modifier.width(6.dp))
                    Text(
                        text = stringResource(R.string.action_system_share),
                        fontFamily = PlusJakartaSansFamily,
                        fontWeight = FontWeight.SemiBold,
                        fontSize = 13.sp
                    )
                }
            }

            Spacer(modifier = Modifier.height(10.dp))

            OutlinedButton(
                onClick = {
                    view.performTactileConfirm()
                    val exported = PollCardImageExporter.exportAndShare(context, room)
                    if (!exported) {
                        Toast.makeText(context, "Unable to export poll card image", Toast.LENGTH_SHORT).show()
                    }
                },
                modifier = Modifier
                    .fillMaxWidth()
                    .height(44.dp)
                    .testTag("popover_export_card_image_button"),
                shape = RoundedCornerShape(12.dp),
                border = BorderStroke(1.dp, colors.vermilion.copy(alpha = 0.45f))
            ) {
                Icon(
                    imageVector = Icons.Outlined.Image,
                    contentDescription = null,
                    tint = colors.vermilion,
                    modifier = Modifier.size(16.dp)
                )
                Spacer(modifier = Modifier.width(8.dp))
                Text(
                    text = "Export Poll Card (Image)",
                    fontFamily = PlusJakartaSansFamily,
                    fontWeight = FontWeight.SemiBold,
                    fontSize = 13.sp,
                    color = colors.inkPrimary
                )
            }

            Spacer(modifier = Modifier.height(10.dp))

            OutlinedButton(
                onClick = {
                    view.performTactileTick()
                    val ok = MeldWidgetUpdater.requestPinPollWidget(context)
                    val msg = context.getString(
                        if (ok) R.string.widget_pin_requested else R.string.widget_pin_unsupported
                    )
                    Toast.makeText(context, msg, Toast.LENGTH_SHORT).show()
                },
                modifier = Modifier
                    .fillMaxWidth()
                    .height(44.dp)
                    .testTag("popover_pin_widget_button"),
                shape = RoundedCornerShape(12.dp),
                border = BorderStroke(1.dp, colors.hairline)
            ) {
                Icon(
                    imageVector = Icons.Outlined.Widgets,
                    contentDescription = null,
                    tint = colors.vermilion,
                    modifier = Modifier.size(16.dp)
                )
                Spacer(modifier = Modifier.width(8.dp))
                Text(
                    text = stringResource(R.string.action_pin_widget),
                    fontFamily = PlusJakartaSansFamily,
                    fontWeight = FontWeight.Medium,
                    fontSize = 13.sp,
                    color = colors.inkPrimary
                )
            }
        }
    }
}

@Composable
private fun QrCodeMatrix(
    content: String,
    modifier: Modifier = Modifier
) {
    val matrix = remember(content) {
        val hints = mapOf(EncodeHintType.MARGIN to 0)
        QRCodeWriter().encode(content, BarcodeFormat.QR_CODE, 0, 0, hints)
    }

    Canvas(modifier = modifier) {
        val cols = matrix.width
        val rows = matrix.height
        if (cols <= 0 || rows <= 0) return@Canvas
        val cellSize = size.minDimension / cols.toFloat()
        val moduleColor = Color(0xFF121214)

        for (y in 0 until rows) {
            for (x in 0 until cols) {
                if (matrix.get(x, y)) {
                    drawRoundRect(
                        color = moduleColor,
                        topLeft = Offset(x * cellSize, y * cellSize),
                        size = Size(cellSize * 0.92f, cellSize * 0.92f),
                        cornerRadius = CornerRadius(cellSize * 0.18f, cellSize * 0.18f)
                    )
                }
            }
        }
    }
}
